import { afterEach, expect, it, vi } from 'vitest';
import { observeTimelineViewport } from './timeline-viewport';

afterEach(() => vi.unstubAllGlobals());
it('shares one scroll frame and reads all clip geometry before any paint', () => {
  const frames = new Map<number, FrameRequestCallback>();
  let next = 0;
  vi.stubGlobal('requestAnimationFrame', (fn: FrameRequestCallback) => { frames.set(++next, fn); return next; });
  vi.stubGlobal('cancelAnimationFrame', (id: number) => frames.delete(id));
  const resize = { observe: vi.fn(), unobserve: vi.fn(), disconnect: vi.fn() };
  const visibility = { observe: vi.fn(), unobserve: vi.fn(), disconnect: vi.fn() };
  vi.stubGlobal('ResizeObserver', class { constructor() { return resize; } });
  vi.stubGlobal('IntersectionObserver', class { constructor() { return visibility; } });
  let painted = false;
  const read = () => { expect(painted).toBe(false); return { left: 0, right: 900, top: 0, bottom: 400, width: 900, height: 400 }; };
  const viewport = { getBoundingClientRect: vi.fn(read), addEventListener: vi.fn(), removeEventListener: vi.fn() } as unknown as HTMLElement;
  const paints = Array.from({ length: 200 }, () => vi.fn(() => { painted = true; }));
  const subscriptions = paints.map(paint => observeTimelineViewport(viewport, { getBoundingClientRect: read } as HTMLElement, paint));
  for (const subscription of subscriptions) subscription.schedule();
  expect(frames.size).toBe(1);
  expect(viewport.addEventListener).toHaveBeenCalledTimes(1);
  frames.values().next().value!(0); frames.clear();
  expect(viewport.getBoundingClientRect).toHaveBeenCalledTimes(1);
  expect(paints.every(paint => paint.mock.calls.length === 1)).toBe(true);
  subscriptions.slice(0, -1).forEach(subscription => subscription.unsubscribe());
  expect(resize.disconnect).not.toHaveBeenCalled();
  subscriptions.at(-1)!.schedule(); subscriptions.at(-1)!.unsubscribe();
  expect(frames.size).toBe(0);
  expect(viewport.removeEventListener).toHaveBeenCalledTimes(1);
  expect(resize.disconnect).toHaveBeenCalledTimes(1);
  expect(visibility.disconnect).toHaveBeenCalledTimes(1);
});
