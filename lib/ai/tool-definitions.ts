export type EditorToolName = keyof typeof EDITOR_TOOL_DEFINITIONS;
const definitions = new Map<string, ToolBehavior>(Object.entries(EDITOR_TOOL_DEFINITIONS));
export const toolBehavior = (name: string) => definitions.get(name);

/** Fail at toolkit startup if a registration omits its definition or metadata. */
export function assertToolDefinitions(tools: Record<EditorToolName, { metadata?: unknown }>) {
  for (const [name, tool] of Object.entries(tools)) {
    if (!definitions.has(name) || tool.metadata !== definitions.get(name)) throw new Error(`Tool ${name} must register its shared behavior metadata.`);
  }
  for (const name of definitions.keys()) {
    if (!(name in tools)) throw new Error(`Tool ${name} is classified but not registered.`);
  }
}
