// Markdown is authored in Git; the committed bundle is safe in every runtime.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../lib/ai/skills/', import.meta.url));
const documents = {};
for (const file of readdirSync(root, { recursive: true }).filter(file => file.endsWith('.md')).sort()) {
  const source = readFileSync(root + file, 'utf8');
  const match = /^---\nname: ("[^\n]*")\ndescription: ("[^\n]*")\n---\n([\s\S]*)$/.exec(source);
  if (!match) throw new Error(`Invalid skill frontmatter: ${file}`);
  documents[file] = { name: JSON.parse(match[1]), description: JSON.parse(match[2]), body: match[3] };
}
const output = '// Generated by scripts/bundle-editor-skills.mjs. Edit the Markdown sources.\nexport const skillDocuments: Record<string, { name: string; description: string; body: string }> = ' + JSON.stringify(documents, null, 2) + ';\n';
const target = root + 'documents.generated.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Skill bundle is stale. Run npm run skills:bundle and commit the result.');
} else if (!process.argv.slice(2).length) {
  if (!(() => { try { return readFileSync(target, 'utf8') === output; } catch { return false; } })()) writeFileSync(target, output);
} else throw new Error('Usage: node scripts/bundle-editor-skills.mjs [--check]');
