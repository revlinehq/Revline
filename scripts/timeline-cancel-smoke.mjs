import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/home/sonic/.cache/puppeteer/chrome/linux-155.0.8059.39/chrome-linux64/chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 1000 });
const wait = ms => new Promise(r => setTimeout(r, ms));
const bounds = selector => page.$eval(selector, el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; });
const failures = [];
try {
 await page.goto('http://localhost:3001/editor/demo', { waitUntil: 'domcontentloaded' });
 await page.waitForFunction(() => document.querySelector('hyperframes-player')?.ready);
 const clip = '.clip-caption';
 const before = await bounds(clip);
 await page.mouse.move(before.x + 30, before.y + before.height / 2);
 await page.mouse.down();
 await page.mouse.move(before.x + 110, before.y + before.height / 2, { steps: 8 });
 await wait(100);
 await page.keyboard.press('Escape');
 if (await page.evaluate(() => document.body.style.cursor) !== '') failures.push('Escape must restore the cursor immediately');
 await page.mouse.up(); await wait(200);
 const after = await bounds(clip);
 if (Math.abs(after.x - before.x) > 1 || Math.abs(after.width - before.width) > 1) failures.push('Escape must discard the drag');
 const handle = await bounds(`${clip} .clip-trim.right`);
 await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
 await page.mouse.down(); await page.mouse.move(handle.x - 40, handle.y + handle.height / 2, { steps: 8 }); await wait(100);
 await page.evaluate(() => window.dispatchEvent(new Event('blur')));
 if (await page.evaluate(() => document.body.style.cursor) !== '') failures.push('Window blur must cancel trimming');
 await page.mouse.up(); await wait(200);
 if (Math.abs((await bounds(clip)).width - after.width) > 1) failures.push('A canceled trim must not persist');
 const marker = await bounds('.timeline-playhead-cap');
 const body = await bounds('.timeline-body');
 if (marker.x < body.x - 0.5) failures.push('The marker head must fit over the header corner at time zero');
 assert.deepEqual(failures, []);
 console.log('Timeline gesture check passed: Escape, blur, canceled edits, and marker bounds.');
} finally { await browser.close(); }
